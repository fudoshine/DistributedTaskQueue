var (
	ErrDuplicateJob    = errors.New("job execution skipped: already completed")
	ErrJobAlreadyOwned = errors.New("job execution skipped: another worker owns this job")
	ErrJobNotReady     = errors.New("job execution skipped: not queued or dependencies are incomplete")
	ErrTerminalJob     = errors.New("job execution skipped: job is terminal")
	ErrLeaseLost       = errors.New("job execution skipped: lease is no longer owned by this attempt")
	ErrStaleDelivery   = errors.New("job execution skipped: delivery is no longer current")
	ErrRelayLeaseLost  = errors.New("outbox relay no longer owns this delivery")
	// ErrJobNotFound means TryStartJob was called for a taskID with no
	// corresponding processed_jobs row. Under this system's design that
	// should never happen — every task is created in Postgres via CreateJob
	// BEFORE its ID is ever pushed onto the Redis queue — so seeing this
	// error means something enqueued an ID directly into Redis without
	// going through the proper creation path, or the row was deleted out
	// from under a live task.
	ErrJobNotFound = errors.New("job execution failed: no processed_jobs row found for taskID")
)

// Task represents a single unit of work to be created in Postgres before
// its ID is enqueued onto Redis. WorkflowID and ParentIDs model the DAG
// structure: every task belongs to exactly one workflow, and may optionally
// have parent tasks it depends on (must complete before this runs).
type Task struct {
	ID         uuid.UUID
	WorkflowID uuid.UUID
	ParentIDs  []uuid.UUID // empty slice for root tasks in a workflow
	TaskType   string
	Payload    json.RawMessage
	MaxRetries int // 0 means "use the schema default (3)"
}
type Workflow struct {
	ID        uuid.UUID
	Name      string
	Status    domain.WorkflowStatus
	CreatedAt time.Time
	UpdatedAt time.Time
}
type JobRow struct {
	ID             uuid.UUID
	WorkflowID     uuid.UUID
	ParentIDs      []uuid.UUID
	TaskType       string
	Status         domain.TaskStatus
	CurrentRetries int
	MaxRetries     int
	ErrorLog       *string
	CreatedAt      time.Time
	ProcessedAt    *time.Time
	AvailableAt    time.Time
}
type JobRepository struct {
	pool *pgxpool.Pool
}

// JobClaim identifies one bounded execution attempt. The lease token is a
// fencing token: every heartbeat, completion, and failure update must present
// this exact value, so a stale worker cannot mutate a reclaimed job.
type JobClaim struct {
	LeaseToken uuid.UUID
	Attempt    int
}

// Delivery is an immutable publication request held in Postgres until the
// relay has appended it to the broker. Generation distinguishes retries and
// recovery from earlier messages for the same logical job.
type Delivery struct {
	OutboxID   uuid.UUID
	TaskID     uuid.UUID
	DeliveryID uuid.UUID
	Generation int
	QueueName  string
}

type RecoveryAction int

const (
	// RecoveryKeepInflight means the lease is still active; Redis must not move
	// the message even if its original visibility timestamp is old.
	RecoveryKeepInflight RecoveryAction = iota
	// RecoveryRequeue means the durable lease expired and Redis may republish.
	RecoveryRequeue
	// RecoveryAcknowledge means the job is terminal or missing; discard the
	// stale Redis inflight entry.
	RecoveryAcknowledge
)

func NewJobRepository(pool *pgxpool.Pool) *JobRepository {
	return &JobRepository{pool: pool}
}

// CreateWorkflow inserts a new workflow row and returns its generated ID.
// Call this once per logical batch of related tasks before creating the
// tasks themselves, since processed_jobs.workflow_id is NOT NULL with a
// foreign key into workflows.
func (r *JobRepository) CreateWorkflow(ctx context.Context, name string) (uuid.UUID, error) {
	var id uuid.UUID
	query := `
		INSERT INTO workflows (name, status)
		VALUES ($1, $2)
		RETURNING id;
	`
	if err := r.pool.QueryRow(ctx, query, name, domain.WorkflowStatusPending).Scan(&id); err != nil {
		metrics.JobRepoErrors.WithLabelValues("_workflow", "CreateWorkflow").Inc()
		return uuid.Nil, fmt.Errorf("failed to create workflow %q: %w", name, err)
	}
	metrics.WorkflowsCreated.Inc()
	return id, nil
}

// CreateJob inserts a processed_jobs row before its ID can be published to
// Redis. Root jobs begin QUEUED; dependent jobs remain PENDING until all
// parents have completed.
//
// task.ID is generated by the caller (uuid.New()) rather than by Postgres,
// because the same ID is used as the Redis queue member — Redis and
// Postgres need to agree on task identity before either one sees the task.
func (r *JobRepository) CreateJob(ctx context.Context, queueName string, task Task) error {
	payload := task.Payload
	if payload == nil {
		payload = json.RawMessage(`{}`)
	}

	tx, err := r.pool.Begin(ctx)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CreateJob").Inc()
		return fmt.Errorf("failed to begin transaction: %w", err)
	}
	defer tx.Rollback(ctx)

	status := domain.TaskStatusPending
	if len(task.ParentIDs) == 0 {
		status = domain.TaskStatusQueued
	}

	// Insert the job
	query := `
		INSERT INTO processed_jobs (id, workflow_id, task_type, status, task_details, max_retries)
		VALUES ($1, $2, $3, $4, $5, COALESCE(NULLIF($6, 0), 3));
	`
	_, err = tx.Exec(ctx, query,
		task.ID, task.WorkflowID, task.TaskType, status, payload, task.MaxRetries,
	)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CreateJob").Inc()
		return fmt.Errorf("failed to create job %s: %w", task.ID, err)
	}

	// Insert parent dependencies if any
	if len(task.ParentIDs) > 0 {
		depQuery := `
			INSERT INTO job_dependencies (child_job_id, parent_job_id)
			VALUES ($1, $2);
		`
		for _, parentID := range task.ParentIDs {
			_, err = tx.Exec(ctx, depQuery, task.ID, parentID)
			if err != nil {
				metrics.JobRepoErrors.WithLabelValues(queueName, "CreateJob").Inc()
				return fmt.Errorf("failed to create dependency %s -> %s: %w", parentID, task.ID, err)
			}
		}
	} else {
		// Root task (no parents) — write outbox row in the same transaction.
		// The outbox relay will enqueue this to Redis. This guarantees atomicity:
		// either both processed_jobs and outbox land, or neither does.
		_, err = insertDelivery(ctx, tx, task.ID, queueName, 0, time.Now())
		if err != nil {
			metrics.JobRepoErrors.WithLabelValues(queueName, "CreateJob").Inc()
			return fmt.Errorf("failed to write outbox row for task %s: %w", task.ID, err)
		}
	}

	if err := tx.Commit(ctx); err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CreateJob").Inc()
		return fmt.Errorf("failed to commit job creation: %w", err)
	}

	return nil
}

// TryStartJob atomically claims an eligible job. QUEUED is the only claimable
// state. The dependency predicate is checked at claim time as a final guard
// against stale or externally injected Redis messages.
func (r *JobRepository) TryStartJob(ctx context.Context, queueName, taskID, deliveryID string, generation int, leaseTTL time.Duration) (JobClaim, error) {
	id, err := uuid.Parse(taskID)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "TryStartJob").Inc()
		return JobClaim{}, fmt.Errorf("taskID %q is not a valid UUID: %w", taskID, err)
	}
	parsedDeliveryID, err := uuid.Parse(deliveryID)
	if err != nil {
		return JobClaim{}, fmt.Errorf("deliveryID %q is not a valid UUID: %w", deliveryID, err)
	}
	if leaseTTL <= 0 {
		return JobClaim{}, fmt.Errorf("lease TTL must be positive")
	}

	tx, err := r.pool.Begin(ctx)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "TryStartJob").Inc()
		return JobClaim{}, fmt.Errorf("failed to begin idempotency transaction: %w", err)
	}
	defer tx.Rollback(ctx) // no-op if Commit succeeds first

	claim := JobClaim{LeaseToken: uuid.New()}
	query := `
		UPDATE processed_jobs AS job
		SET status = $2,
		    lease_token = $3,
		    lease_expires_at = NOW() + $4::interval,
		    attempt_number = attempt_number + 1
		WHERE job.id = $1
		  AND job.status = $5
		  AND job.delivery_generation = $7
		  AND EXISTS (
			  SELECT 1 FROM outbox delivery
			  WHERE delivery.task_id = job.id
			    AND delivery.generation = $7
			    AND delivery.delivery_id = $8
		  )
		  AND job.available_at <= NOW()
		  AND NOT EXISTS (
			  SELECT 1
			  FROM job_dependencies edge
			  JOIN processed_jobs parent ON parent.id = edge.parent_job_id
			  WHERE edge.child_job_id = job.id
			    AND parent.status <> $6
		  )
		RETURNING lease_token, attempt_number;
		`
	err = tx.QueryRow(ctx, query, id, domain.TaskStatusRunning, claim.LeaseToken, leaseTTL.String(), domain.TaskStatusQueued, domain.TaskStatusCompleted, generation, parsedDeliveryID).Scan(&claim.LeaseToken, &claim.Attempt)
	if err != nil {
		if !errors.Is(err, pgx.ErrNoRows) {
			metrics.JobRepoErrors.WithLabelValues(queueName, "TryStartJob").Inc()
			return JobClaim{}, fmt.Errorf("failed to claim job %s: %w", taskID, err)
		}

		var status domain.TaskStatus
		var currentGeneration int
		err = tx.QueryRow(ctx, `SELECT status, delivery_generation FROM processed_jobs WHERE id = $1;`, id).Scan(&status, &currentGeneration)
		if errors.Is(err, pgx.ErrNoRows) {
			metrics.JobRepoErrors.WithLabelValues(queueName, "TryStartJob").Inc()
			return JobClaim{}, ErrJobNotFound
		}
		if currentGeneration != generation {
			return JobClaim{}, ErrStaleDelivery
		}
		if err != nil {
			metrics.JobRepoErrors.WithLabelValues(queueName, "TryStartJob").Inc()
			return JobClaim{}, fmt.Errorf("failed to inspect unclaimable job %s: %w", taskID, err)
		}

		switch status {
		case domain.TaskStatusCompleted:
			metrics.JobsDuplicateSkipped.WithLabelValues(queueName).Inc()
			return JobClaim{}, ErrDuplicateJob
		case domain.TaskStatusFailed, domain.TaskStatusCancelled:
			return JobClaim{}, ErrTerminalJob
		case domain.TaskStatusRunning:
			return JobClaim{}, ErrJobAlreadyOwned
		default:
			return JobClaim{}, ErrJobNotReady
		}
	}

	slog.Info("[IDEMPOTENCY] job claimed", "taskId", taskID, "attempt", claim.Attempt, "leaseToken", claim.LeaseToken)

	if err := tx.Commit(ctx); err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "TryStartJob").Inc()
		return JobClaim{}, fmt.Errorf("failed to commit idempotency transaction: %w", err)
	}

	return claim, nil
}

// RecordFailure increments the retry counter and stores the latest error,
// transitioning status to FAILED once max_retries is reached. Returns the
// updated (currentRetries, maxRetries) so the caller can decide retry vs DLQ.
func (r *JobRepository) RecordFailure(ctx context.Context, queueName, taskID string, leaseToken uuid.UUID, errLog string) (currentRetries int, maxRetries int, err error) {
	id, parseErr := uuid.Parse(taskID)
	if parseErr != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "RecordFailure").Inc()
		return 0, 0, fmt.Errorf("taskID %q is not a valid UUID: %w", taskID, parseErr)
	}

	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return 0, 0, fmt.Errorf("begin failure transaction: %w", err)
	}
	defer tx.Rollback(ctx)

	query := `
		UPDATE processed_jobs
		SET current_retries = current_retries + 1,
		    error_log = $2,
	    status = CASE
	        WHEN current_retries + 1 >= max_retries THEN $3
	        ELSE $4
	    END,
		    available_at = CASE
				WHEN current_retries + 1 >= max_retries THEN NOW()
				ELSE NOW() + make_interval(secs => ((1::bigint << (current_retries + 1))::double precision))
			END,
			lease_token = NULL,
			lease_expires_at = NULL,
			delivery_generation = CASE
				WHEN current_retries + 1 >= max_retries THEN delivery_generation
				ELSE delivery_generation + 1
			END
		WHERE id = $1
		  AND status = $5
		  AND lease_token = $6
		  AND lease_expires_at > NOW()
		RETURNING current_retries, max_retries, status, delivery_generation, available_at;
	`
	var status domain.TaskStatus
	var generation int
	var availableAt time.Time
	err = tx.QueryRow(ctx, query, id, errLog, domain.TaskStatusFailed, domain.TaskStatusQueued, domain.TaskStatusRunning, leaseToken).Scan(&currentRetries, &maxRetries, &status, &generation, &availableAt)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return 0, 0, ErrLeaseLost
		}
		metrics.JobRepoErrors.WithLabelValues(queueName, "RecordFailure").Inc()
		return 0, 0, fmt.Errorf("failed to record failure for task %s: %w", taskID, err)
	}
	if status == domain.TaskStatusQueued {
		if _, err := insertDelivery(ctx, tx, id, queueName, generation, availableAt); err != nil {
			return 0, 0, fmt.Errorf("schedule retry delivery: %w", err)
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return 0, 0, fmt.Errorf("commit failure transaction: %w", err)
	}
	if currentRetries >= maxRetries {
		metrics.JobsFailedTerminal.WithLabelValues(queueName).Inc()
	}
	return currentRetries, maxRetries, nil
}

func insertDelivery(ctx context.Context, tx pgx.Tx, taskID uuid.UUID, queueName string, generation int, notBefore time.Time) (Delivery, error) {
	delivery := Delivery{DeliveryID: uuid.New(), TaskID: taskID, QueueName: queueName, Generation: generation}
	err := tx.QueryRow(ctx, `
		INSERT INTO outbox (task_id, queue_name, delivery_id, generation, not_before, delivered)
		VALUES ($1, $2, $3, $4, $5, FALSE)
		RETURNING id;
	`, taskID, queueName, delivery.DeliveryID, generation, notBefore).Scan(&delivery.OutboxID)
	return delivery, err
}

// RenewLease extends an active attempt using the database clock. It returns
// false when another attempt reclaimed the job or the lease already expired.
func (r *JobRepository) RenewLease(ctx context.Context, queueName, taskID string, leaseToken uuid.UUID, leaseTTL time.Duration) (bool, error) {
	id, err := uuid.Parse(taskID)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "RenewLease").Inc()
		return false, fmt.Errorf("taskID %q is not a valid UUID: %w", taskID, err)
	}
	if leaseTTL <= 0 {
		return false, fmt.Errorf("lease TTL must be positive")
	}

	tag, err := r.pool.Exec(ctx, `
		UPDATE processed_jobs
		SET lease_expires_at = NOW() + $3::interval
		WHERE id = $1
		  AND status = $4
		  AND lease_token = $2
		  AND lease_expires_at > NOW();
	`, id, leaseToken, leaseTTL.String(), domain.TaskStatusRunning)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "RenewLease").Inc()
		return false, fmt.Errorf("failed to renew lease for job %s: %w", taskID, err)
	}
	return tag.RowsAffected() == 1, nil
}

// RecoverExpiredJob tells the janitor whether a Redis inflight entry may be
// moved. The Redis visibility timestamp is only a prompt: recovery happens
// solely after the durable Postgres lease has expired.
func (r *JobRepository) RecoverExpiredJob(ctx context.Context, queueName, taskID string) (RecoveryAction, error) {
	id, err := uuid.Parse(taskID)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "RecoverExpiredJob").Inc()
		return RecoveryKeepInflight, fmt.Errorf("taskID %q is not a valid UUID: %w", taskID, err)
	}

	tag, err := r.pool.Exec(ctx, `
		UPDATE processed_jobs
		SET status = $2,
		    available_at = NOW(),
		    lease_token = NULL,
		    lease_expires_at = NULL
		WHERE id = $1
		  AND status = $3
		  AND lease_expires_at <= NOW();
	`, id, domain.TaskStatusQueued, domain.TaskStatusRunning)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "RecoverExpiredJob").Inc()
		return RecoveryKeepInflight, fmt.Errorf("failed to recover expired job %s: %w", taskID, err)
	}
	if tag.RowsAffected() == 1 {
		return RecoveryRequeue, nil
	}

	var status domain.TaskStatus
	err = r.pool.QueryRow(ctx, `SELECT status FROM processed_jobs WHERE id = $1;`, id).Scan(&status)
	if errors.Is(err, pgx.ErrNoRows) {
		return RecoveryAcknowledge, nil
	}
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "RecoverExpiredJob").Inc()
		return RecoveryKeepInflight, fmt.Errorf("failed to inspect abandoned job %s: %w", taskID, err)
	}
	if status == domain.TaskStatusQueued {
		// The process may have crashed after changing Postgres to QUEUED but
		// before it republished the Redis entry. Repeating the move is safe.
		return RecoveryRequeue, nil
	}
	if status == domain.TaskStatusRunning {
		return RecoveryKeepInflight, nil
	}
	return RecoveryAcknowledge, nil
}

// CompleteJobAndScheduleChildren durably completes a job and promotes every
// newly-ready child to QUEUED in the same PostgreSQL transaction. Each
// promoted child receives an outbox entry, so Redis publication is retried by
// the outbox relay instead of being coupled to a worker's process lifetime.
//
// Completion for a workflow is serialized with a transaction advisory lock.
// This matters for a multi-parent child: two parents may finish concurrently;
// without serialization each transaction could observe the other as RUNNING
// and neither would promote the child.
func (r *JobRepository) CompleteJobAndScheduleChildren(ctx context.Context, queueName, taskID string, leaseToken uuid.UUID) ([]string, error) {
	id, err := uuid.Parse(taskID)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
		return nil, fmt.Errorf("taskID %q is not a valid UUID: %w", taskID, err)
	}

	tx, err := r.pool.Begin(ctx)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
		return nil, fmt.Errorf("failed to begin completion transaction: %w", err)
	}
	defer tx.Rollback(ctx)

	var workflowID uuid.UUID
	err = tx.QueryRow(ctx, `
		UPDATE processed_jobs
		SET status = $2,
		    processed_at = NOW(),
		    lease_token = NULL,
		    lease_expires_at = NULL
		WHERE id = $1
		  AND status = $3
		  AND lease_token = $4
		  AND lease_expires_at > NOW()
		RETURNING workflow_id;
	`, id, domain.TaskStatusCompleted, domain.TaskStatusRunning, leaseToken).Scan(&workflowID)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
		if errors.Is(err, pgx.ErrNoRows) {
			return nil, ErrLeaseLost
		}
		return nil, fmt.Errorf("failed to complete job %s: %w", taskID, err)
	}

	if _, err := tx.Exec(ctx, `SELECT pg_advisory_xact_lock(hashtextextended($1::text, 0));`, workflowID); err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
		return nil, fmt.Errorf("failed to lock workflow %s for completion: %w", workflowID, err)
	}

	rows, err := tx.Query(ctx, `
		WITH ready_children AS (
			SELECT DISTINCT child.id
			FROM job_dependencies edge
			JOIN processed_jobs child ON child.id = edge.child_job_id
			WHERE edge.parent_job_id = $1
			  AND child.status = $2
			  AND NOT EXISTS (
				SELECT 1
				FROM job_dependencies parent_edge
				JOIN processed_jobs parent ON parent.id = parent_edge.parent_job_id
				WHERE parent_edge.child_job_id = child.id
				  AND parent.status <> $3
			  )
		), promoted_children AS (
			UPDATE processed_jobs child
			SET status = $4,
			    available_at = NOW()
			FROM ready_children ready
			WHERE child.id = ready.id AND child.status = $2
			RETURNING child.id
		)
		INSERT INTO outbox (task_id, queue_name, delivery_id, generation, not_before, delivered)
		SELECT id, $5, uuid_generate_v4(), 0, NOW(), FALSE FROM promoted_children
		ON CONFLICT (task_id, generation) DO NOTHING
		RETURNING task_id;
	`, id, domain.TaskStatusPending, domain.TaskStatusCompleted, domain.TaskStatusQueued, queueName)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
		return nil, fmt.Errorf("failed to schedule children of job %s: %w", taskID, err)
	}
	defer rows.Close()

	children := make([]string, 0)
	for rows.Next() {
		var childID uuid.UUID
		if err := rows.Scan(&childID); err != nil {
			metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
			return nil, fmt.Errorf("failed to scan scheduled child of job %s: %w", taskID, err)
		}
		children = append(children, childID.String())
	}
	if err := rows.Err(); err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
		return nil, fmt.Errorf("failed to schedule children of job %s: %w", taskID, err)
	}

	if err := tx.Commit(ctx); err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "CompleteJobAndScheduleChildren").Inc()
		return nil, fmt.Errorf("failed to commit completion of job %s: %w", taskID, err)
	}

	metrics.JobsCompleted.WithLabelValues(queueName).Inc()
	if len(children) > 0 {
		metrics.ChildrenEnqueued.WithLabelValues(queueName).Add(float64(len(children)))
	}
	return children, nil
}

// MarkAsCancelledCascading recursively cancels all descendant tasks when a
// parent fails. This enforces strict topological ordering: if any required
// parent fails, all downstream tasks are blocked and should be cancelled.
//
// For DAGs with multiple parents (AND semantics): if ANY parent fails, children
// cannot run because they need outputs from ALL parents.
func (r *JobRepository) MarkAsCancelledCascading(ctx context.Context, queueName, failedTaskID string) error {
	id, err := uuid.Parse(failedTaskID)
	if err != nil {
		return fmt.Errorf("taskID %q is not a valid UUID: %w", failedTaskID, err)
	}

	// Recursively find and cancel all descendants of the failed task.
	// This uses an explicit path array to avoid cycles and stays compatible with
	// PostgreSQL 14's recursive CTE support.
	query := `
		WITH RECURSIVE descendants AS (
			-- Base case: direct children of failed task
			SELECT child_job_id, ARRAY[child_job_id] AS path
			FROM job_dependencies
			WHERE parent_job_id = $1
			
			UNION ALL
			
			-- Recursive case: children of children
			SELECT jd.child_job_id, d.path || jd.child_job_id
			FROM job_dependencies jd
			INNER JOIN descendants d ON jd.parent_job_id = d.child_job_id
			WHERE NOT jd.child_job_id = ANY(d.path)
		)
		UPDATE processed_jobs
		SET status = $2,
		    lease_token = NULL,
		    lease_expires_at = NULL
		FROM descendants
		WHERE processed_jobs.id = descendants.child_job_id
		  AND processed_jobs.status IN ($3, $4, $5);  -- Only cancel PENDING/QUEUED/RUNNING
	`

	tag, err := r.pool.Exec(ctx, query, id, domain.TaskStatusCancelled, domain.TaskStatusPending, domain.TaskStatusQueued, domain.TaskStatusRunning)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues(queueName, "MarkAsCancelledCascading").Inc()
		return fmt.Errorf("failed to mark descendants as CANCELLED: %w", err)
	}

	cancelled := tag.RowsAffected()
	if cancelled > 0 {
		metrics.TasksCancelledCascade.WithLabelValues(queueName).Add(float64(cancelled))
		slog.Warn("[CASCADE] cancelled all descendants of failed parent", "parentId", failedTaskID, "cancelledCount", cancelled)
	}
	return nil
}

// UpdateWorkflowStatus checks all jobs in a workflow and updates the workflow
// status based on aggregate job states:
// - RUNNING: If any job is RUNNING
// - FAILED: If all jobs are terminal and at least one FAILED
// - COMPLETED: If all jobs are COMPLETED
// - PENDING: Otherwise
func (r *JobRepository) UpdateWorkflowStatus(ctx context.Context, workflowID uuid.UUID) error {
	query := `
		UPDATE workflows w
		SET status = CASE
			-- If any job is RUNNING, workflow is RUNNING
			WHEN EXISTS (
				SELECT 1 FROM processed_jobs 
				WHERE workflow_id = $1 AND status = $2
			) THEN $2
			
			-- If all jobs are terminal (COMPLETED/FAILED/CANCELLED)
			WHEN NOT EXISTS (
				SELECT 1 FROM processed_jobs 
				WHERE workflow_id = $1 
				  AND status NOT IN ($3, $4, $5)
			) THEN 
				-- If any job FAILED, workflow FAILED
				CASE 
					WHEN EXISTS (
						SELECT 1 FROM processed_jobs 
						WHERE workflow_id = $1 AND status = $4
					) THEN $4
					-- Otherwise all COMPLETED/CANCELLED, workflow COMPLETED
					ELSE $3
				END
			
			-- Otherwise keep current status (PENDING or RUNNING)
			ELSE w.status
		END,
		updated_at = NOW()
		WHERE id = $1
		  AND status != CASE
			WHEN EXISTS (
				SELECT 1 FROM processed_jobs 
				WHERE workflow_id = $1 AND status = $2
			) THEN $2
			WHEN NOT EXISTS (
				SELECT 1 FROM processed_jobs 
				WHERE workflow_id = $1 
				  AND status NOT IN ($3, $4, $5)
			) THEN 
				CASE 
					WHEN EXISTS (
						SELECT 1 FROM processed_jobs 
						WHERE workflow_id = $1 AND status = $4
					) THEN $4
					ELSE $3
				END
			ELSE w.status
		END;  -- Only update if status actually changed
	`

	tag, err := r.pool.Exec(ctx, query, workflowID, domain.TaskStatusRunning, domain.TaskStatusCompleted, domain.TaskStatusFailed, domain.TaskStatusCancelled)
	if err != nil {
		metrics.JobRepoErrors.WithLabelValues("_workflow", "UpdateWorkflowStatus").Inc()
		return fmt.Errorf("failed to update workflow status: %w", err)
	}

	if tag.RowsAffected() > 0 {
		// Check what the new status is to increment appropriate metric
		var newStatus domain.TaskStatus
		checkQuery := `SELECT status FROM workflows WHERE id = $1;`
		if err := r.pool.QueryRow(ctx, checkQuery, workflowID).Scan(&newStatus); err == nil {
			switch newStatus {
			case domain.TaskStatusCompleted:
				metrics.WorkflowsCompleted.Inc()
				slog.Info("[WORKFLOW] completed", "workflowId", workflowID)
			case domain.TaskStatusFailed:
				metrics.WorkflowsFailed.Inc()
				slog.Warn("[WORKFLOW] failed", "workflowId", workflowID)
			default:
				slog.Info("[WORKFLOW] status updated", "workflowId", workflowID, "status", newStatus)
			}
		}
	}
	return nil
}

// ClaimPendingOutbox leases due rows so multiple relay replicas never publish
// the same row concurrently. A relay crash merely lets the short lease expire;
// a repeated publication is safe because the delivery ID is immutable.
func (r *JobRepository) ClaimPendingOutbox(ctx context.Context, limit int, leaseTTL time.Duration) ([]Delivery, uuid.UUID, error) {
	if limit < 1 || leaseTTL <= 0 {
		return nil, uuid.Nil, fmt.Errorf("invalid outbox claim limit or lease TTL")
	}
	token := uuid.New()
	rows, err := r.pool.Query(ctx, `
		WITH due AS (
			SELECT id FROM outbox
			WHERE delivered = FALSE
			  AND not_before <= NOW()
			  AND (relay_lease_expires_at IS NULL OR relay_lease_expires_at <= NOW())
			ORDER BY not_before, created_at
			FOR UPDATE SKIP LOCKED
			LIMIT $1
		)
		UPDATE outbox entry
		SET relay_lease_token = $2,
		    relay_lease_expires_at = NOW() + $3::interval
		FROM due
		WHERE entry.id = due.id
		RETURNING entry.id, entry.task_id, entry.delivery_id, entry.generation, entry.queue_name;
	`, limit, token, leaseTTL.String())
	if err != nil {
		return nil, uuid.Nil, fmt.Errorf("claim due outbox rows: %w", err)
	}
	defer rows.Close()
	entries := make([]Delivery, 0)
	for rows.Next() {
		var entry Delivery
		if err := rows.Scan(&entry.OutboxID, &entry.TaskID, &entry.DeliveryID, &entry.Generation, &entry.QueueName); err != nil {
			return nil, uuid.Nil, fmt.Errorf("scan claimed outbox row: %w", err)
		}
		entries = append(entries, entry)
	}
	return entries, token, rows.Err()
}

func (r *JobRepository) MarkOutboxDelivered(ctx context.Context, outboxID, relayToken uuid.UUID) error {
	tag, err := r.pool.Exec(ctx, `
		UPDATE outbox
		SET delivered = TRUE, delivered_at = NOW(), relay_lease_token = NULL, relay_lease_expires_at = NULL
		WHERE id = $1 AND delivered = FALSE AND relay_lease_token = $2;
	`, outboxID, relayToken)
	if err != nil {
		return fmt.Errorf("mark outbox row %s delivered: %w", outboxID, err)
	}
	if tag.RowsAffected() != 1 {
		return ErrRelayLeaseLost
	}
	return nil
}

func (r *JobRepository) ReleaseOutboxLease(ctx context.Context, outboxID, relayToken uuid.UUID) error {
	_, err := r.pool.Exec(ctx, `
		UPDATE outbox SET relay_lease_token = NULL, relay_lease_expires_at = NULL
		WHERE id = $1 AND delivered = FALSE AND relay_lease_token = $2;
	`, outboxID, relayToken)
	return err
}

// RecoverExpiredLeases durably schedules a new delivery generation for every
// expired running attempt. It does not depend on Redis pending state, so a
// broker outage or a lost old PEL entry cannot strand a RUNNING job.
func (r *JobRepository) RecoverExpiredLeases(ctx context.Context, queueName string, limit int) ([]Delivery, error) {
	if limit < 1 {
		return nil, fmt.Errorf("recovery limit must be positive")
	}
	rows, err := r.pool.Query(ctx, `
		WITH expired AS (
			SELECT id, delivery_generation + 1 AS next_generation
			FROM processed_jobs
			WHERE status = $1 AND lease_expires_at <= NOW()
			ORDER BY lease_expires_at
			FOR UPDATE SKIP LOCKED
			LIMIT $2
		), recovered AS (
			UPDATE processed_jobs job
			SET status = $3, available_at = NOW(), lease_token = NULL, lease_expires_at = NULL,
			    delivery_generation = expired.next_generation
			FROM expired WHERE job.id = expired.id
			RETURNING job.id, job.delivery_generation
		), published AS (
			INSERT INTO outbox (task_id, queue_name, delivery_id, generation, not_before, delivered)
			SELECT id, $4, uuid_generate_v4(), delivery_generation, NOW(), FALSE FROM recovered
			RETURNING id, task_id, delivery_id, generation, queue_name
		)
		SELECT id, task_id, delivery_id, generation, queue_name FROM published;
	`, domain.TaskStatusRunning, limit, domain.TaskStatusQueued, queueName)
	if err != nil {
		return nil, fmt.Errorf("recover expired leases: %w", err)
	}
	defer rows.Close()
	entries := make([]Delivery, 0)
	for rows.Next() {
		var entry Delivery
		if err := rows.Scan(&entry.OutboxID, &entry.TaskID, &entry.DeliveryID, &entry.Generation, &entry.QueueName); err != nil {
			return nil, fmt.Errorf("scan recovered delivery: %w", err)
		}
		entries = append(entries, entry)
	}
	return entries, rows.Err()
}

// RecoverIdleDelivery handles a PEL entry whose consumer stopped before it
// claimed the job. Running jobs with a live DB lease remain untouched; all
// other current queued deliveries get a new durable generation before the old
// Stream entry is acknowledged.
func (r *JobRepository) RecoverIdleDelivery(ctx context.Context, queueName, taskID string, generation int) (RecoveryAction, error) {
	id, err := uuid.Parse(taskID)
	if err != nil {
		return RecoveryAcknowledge, fmt.Errorf("taskID %q is not a valid UUID: %w", taskID, err)
	}
	tx, err := r.pool.Begin(ctx)
	if err != nil {
		return RecoveryKeepInflight, fmt.Errorf("begin idle-delivery recovery: %w", err)
	}
	defer tx.Rollback(ctx)
	var status domain.TaskStatus
	var currentGeneration int
	var availableAt time.Time
	err = tx.QueryRow(ctx, `
		SELECT status, delivery_generation, available_at
		FROM processed_jobs WHERE id = $1 FOR UPDATE;
	`, id).Scan(&status, &currentGeneration, &availableAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return RecoveryAcknowledge, nil
	}
	if err != nil {
		return RecoveryKeepInflight, fmt.Errorf("inspect idle delivery: %w", err)
	}
	if currentGeneration != generation || status == domain.TaskStatusCompleted || status == domain.TaskStatusFailed || status == domain.TaskStatusCancelled || status == domain.TaskStatusPending {
		return RecoveryAcknowledge, nil
	}
	if status != domain.TaskStatusQueued && status != domain.TaskStatusRunning {
		return RecoveryAcknowledge, nil
	}
	nextGeneration := currentGeneration + 1
	result, err := tx.Exec(ctx, `
		UPDATE processed_jobs
		SET status = $2, lease_token = NULL, lease_expires_at = NULL, delivery_generation = $3
		WHERE id = $1
		  AND (status <> $4 OR lease_expires_at IS NULL OR lease_expires_at <= NOW());
	`, id, domain.TaskStatusQueued, nextGeneration, domain.TaskStatusRunning)
	if err != nil {
		return RecoveryKeepInflight, fmt.Errorf("reset idle delivery: %w", err)
	}
	if result.RowsAffected() == 0 {
		// PostgreSQL is the clock and the fence. A live lease must remain
		// owned by its worker even when the janitor host clock is ahead.
		return RecoveryKeepInflight, nil
	}
	if _, err := insertDelivery(ctx, tx, id, queueName, nextGeneration, availableAt); err != nil {
		return RecoveryKeepInflight, fmt.Errorf("schedule recovered delivery: %w", err)
	}
	if err := tx.Commit(ctx); err != nil {
		return RecoveryKeepInflight, fmt.Errorf("commit idle-delivery recovery: %w", err)
	}
	return RecoveryRequeue, nil
}

// GetStuckPendingJobs returns task IDs that have been sitting in PENDING status
// for longer than the given threshold. These are candidates for the orphan
// reconciler — they exist in the DB but were never enqueued to Redis (e.g.
// because EnqueueTask failed after CreateJob succeeded).
func (r *JobRepository) GetStuckPendingJobs(ctx context.Context, olderThan time.Duration) ([]string, error) {
	query := `
		SELECT id FROM processed_jobs
		WHERE status = $1
		  AND created_at < NOW() - ($2 || ' seconds')::INTERVAL;
	`
	rows, err := r.pool.Query(ctx, query, domain.TaskStatusPending, int(olderThan.Seconds()))
	if err != nil {
		return nil, fmt.Errorf("failed to query stuck pending jobs: %w", err)
	}
	defer rows.Close()

	var ids []string
	for rows.Next() {
		var id uuid.UUID
		if err := rows.Scan(&id); err != nil {
			return nil, fmt.Errorf("failed to scan pending job id: %w", err)
		}
		ids = append(ids, id.String())
	}
	return ids, rows.Err()
}

// GetWorkflowID retrieves the workflow_id for a given task.
func (r *JobRepository) GetWorkflowID(ctx context.Context, taskID string) (uuid.UUID, error) {
	id, err := uuid.Parse(taskID)
	if err != nil {
		return uuid.Nil, fmt.Errorf("taskID %q is not a valid UUID: %w", taskID, err)
	}

	var workflowID uuid.UUID
	query := `SELECT workflow_id FROM processed_jobs WHERE id = $1;`
	err = r.pool.QueryRow(ctx, query, id).Scan(&workflowID)
	if err != nil {
		return uuid.Nil, fmt.Errorf("failed to get workflow_id for task %s: %w", taskID, err)
	}
	return workflowID, nil
}

func (r *JobRepository) GetWorkflow(ctx context.Context, workflowID uuid.UUID) (Workflow, error) {
	if workflowID == uuid.Nil {
		return Workflow{}, fmt.Errorf("workflowID is nil")
	}

	var workflow Workflow
	query := `SELECT id, name, status, created_at,updated_at FROM workflows WHERE id = $1;`
	err := r.pool.QueryRow(ctx, query, workflowID).Scan(&workflow.ID, &workflow.Name, &workflow.Status, &workflow.CreatedAt, &workflow.UpdatedAt)
	if err != nil {
		return Workflow{}, fmt.Errorf("failed to get workflow for ID %s: %w", workflowID, err)
	}
	return workflow, nil
}

func (r *JobRepository) GetTask(ctx context.Context, taskID uuid.UUID) (JobRow, error) {
	if taskID == uuid.Nil {
		return JobRow{}, fmt.Errorf("taskID is nil")
	}

	var task JobRow
	query := `SELECT id, workflow_id, task_type, status, current_retries, max_retries,
          error_log, created_at, processed_at, available_at
		  FROM processed_jobs
		  WHERE id = $1;`
	err := r.pool.QueryRow(ctx, query, taskID).Scan(
		&task.ID, &task.WorkflowID, &task.TaskType, &task.Status,
		&task.CurrentRetries, &task.MaxRetries,
		&task.ErrorLog, &task.CreatedAt, &task.ProcessedAt, &task.AvailableAt,
	)
	if err != nil {
		return JobRow{}, fmt.Errorf("failed to get Task for ID %s: %w", taskID, err)
	}

	var rows pgx.Rows
	rows, err = r.pool.Query(ctx, `SELECT parent_job_id FROM job_dependencies WHERE child_job_id=$1;`, taskID)
	if err != nil {
		return JobRow{}, fmt.Errorf("failed to get parent IDs for task %s: %w", taskID, err)
	}
	defer rows.Close()
	for rows.Next() {
		var parentID uuid.UUID
		if err := rows.Scan(&parentID); err != nil {
			return JobRow{}, fmt.Errorf("failed to scan parent ID: %w", err)
		}
		task.ParentIDs = append(task.ParentIDs, parentID)
	}
	if err := rows.Err(); err != nil {
		return JobRow{}, fmt.Errorf("parent IDs iteration error: %w", err)
	}
	return task, nil
}
